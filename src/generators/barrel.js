/**
 * Updates barrel (index) files for web components and framework wrappers.
 * Append-only — never removes existing exports.
 *
 * Data-driven: each framework defines its export patterns via a config object,
 * and two generic functions handle tier and root barrel updates.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';

const BARREL_HEADER = '// Auto-generated by @arclux/prism — do not edit manually';

/**
 * Test whether an export for `needle` already exists in barrel `content`.
 * Uses identifier boundaries rather than a plain substring so that a component
 * whose name is a substring of an already-exported one (e.g. `Button` inside
 * `IconButton`) is not mistaken for a duplicate and silently dropped.
 */
function alreadyExported(content, needle) {
  const escaped = needle.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(?<![\\w$])${escaped}(?![\\w$])`).test(content);
}

// ── Framework barrel configs ────────────────────────────────

/**
 * @typedef {Object} BarrelConfig
 * @property {string} barrelExt - barrel file extension (e.g. '.js', '.ts')
 * @property {(meta: import('./parser.js').ComponentMeta) => string} existsCheck
 *   - string to search for in existing content to detect duplicates
 * @property {(meta: import('./parser.js').ComponentMeta) => string} tierExportLines
 *   - the export line(s) to append to a tier barrel
 * @property {(meta: import('./parser.js').ComponentMeta) => string} rootExportLines
 *   - the export line(s) to append to a root barrel
 * @property {string} separator - string between existing content and new lines
 * @property {'root-merge'|'root-append'} [rootStrategy] - WC uses merge into existing tier line
 */

/** Web Components barrel config — special root strategy that merges into existing tier export. */
const wcConfig = {
  barrelExt: '.js',
  existsCheck: (meta) => meta.className,
  tierExportLines: (meta, prefix = 'arc') => {
    const fileName = meta.tag.replace(new RegExp('^' + prefix + '-'), '');
    return `export { ${meta.className} } from './${fileName}.js';`;
  },
  separator: '\n',
  rootStrategy: 'root-merge',
  rootExportLines: (meta) => `export { ${meta.className} } from './${meta.tier}/index.js';`,
};

/** Shared config factory for frameworks that use `export { X } from './X.js'` + type exports. */
function typedJsConfig() {
  return {
    barrelExt: '.ts',
    existsCheck: (meta) => meta.pascalName,
    rootExistsCheck: (meta) => `{ ${meta.pascalName} }`,
    tierExportLines: (meta) => [
      `export { ${meta.pascalName} } from './${meta.pascalName}.js';`,
      `export type { ${meta.pascalName}Props } from './${meta.pascalName}.js';`,
    ].join('\n'),
    separator: '\n\n',
    rootStrategy: 'root-append',
    rootExportLines: (meta) => [
      `export { ${meta.pascalName} } from './${meta.tier}/${meta.pascalName}.js';`,
      `export type { ${meta.pascalName}Props } from './${meta.tier}/${meta.pascalName}.js';`,
    ].join('\n'),
  };
}

/** Shared config factory for SFC frameworks (Vue/Svelte) using `export { default as X }`. */
function sfcConfig(ext) {
  return {
    barrelExt: '.ts',
    existsCheck: (meta) => meta.pascalName,
    rootExistsCheck: (meta) => `{ default as ${meta.pascalName} }`,
    tierExportLines: (meta) =>
      `export { default as ${meta.pascalName} } from './${meta.pascalName}.${ext}';`,
    separator: '\n',
    rootStrategy: 'root-append',
    rootExportLines: (meta) =>
      `export { default as ${meta.pascalName} } from './${meta.tier}/${meta.pascalName}.${ext}';`,
  };
}

/**
 * Plain named-export config (Angular) — no type exports, no default-as.
 * Extensionless specifiers on purpose: ngc emits .mjs whose imports keep the
 * source specifier verbatim, so a '.js' suffix breaks ng-packagr's flatten
 * step ("Could not resolve ./X.js from dist/esm2022/index.mjs").
 */
const angularConfig = {
  barrelExt: '.ts',
  existsCheck: (meta) => meta.pascalName,
  rootExistsCheck: (meta) => `{ ${meta.pascalName} }`,
  tierExportLines: (meta) =>
    `export { ${meta.pascalName} } from './${meta.pascalName}';`,
  separator: '\n',
  rootStrategy: 'root-append',
  rootExportLines: (meta) =>
    `export { ${meta.pascalName} } from './${meta.tier}/${meta.pascalName}';`,
};

const FRAMEWORK_CONFIGS = {
  wc: wcConfig,
  react: typedJsConfig(),
  solid: typedJsConfig(),
  preact: typedJsConfig(),
  vue: sfcConfig('vue'),
  svelte: sfcConfig('svelte'),
  angular: angularConfig,
};

// ── Export statement shape ──────────────────────────────────

/**
 * One `export { … } from './x.js';` statement, anchored at both ends.
 *
 * `[^}]` matches newlines, so this reads a statement written across several
 * lines as happily as a single-line one — provided it is handed the whole
 * statement. Everything below works in statements rather than lines for that
 * reason: a barrel that has been through a formatter wraps its longer exports
 * once they pass the print width, and matching line by line skipped every one
 * of them silently — `barrelExclude` simply had no effect on such a file.
 */
const EXPORT_STATEMENT =
  /^[ \t]*export\s+(?:type\s+)?\{([^}]*)\}\s*from\s*['"](\.[^'"]*)['"];?\s*$/;

/** A line that may open an export-from statement, wrapped or not. */
const EXPORT_OPENER = /^[ \t]*export\s+(?:type\s+)?\{/;

/**
 * Split `content` into chunks: either an export-from statement with its match,
 * or a line to be copied through verbatim. Continuation lines are joined onto
 * their opener until the statement completes; a run that never completes is
 * emitted as plain lines, so an export shape this file does not understand is
 * left alone rather than mangled.
 *
 * @returns {{ raw: string, match?: RegExpMatchArray }[]}
 */
function exportStatements(content) {
  const lines = content.split('\n');
  const chunks = [];

  for (let i = 0; i < lines.length; i++) {
    if (!EXPORT_OPENER.test(lines[i])) {
      chunks.push({ raw: lines[i] });
      continue;
    }

    let raw = lines[i];
    let end = i;
    let match = raw.match(EXPORT_STATEMENT);
    // Stop at the next statement rather than running to end of file, so one
    // malformed export costs its own line and not the rest of the barrel.
    while (
      !match
      && end + 1 < lines.length
      && !/^[ \t]*(?:export|import)\b/.test(lines[end + 1])
    ) {
      raw += '\n' + lines[++end];
      match = raw.match(EXPORT_STATEMENT);
    }

    if (!match) { chunks.push({ raw: lines[i] }); continue; }
    chunks.push({ raw, match });
    i = end;
  }

  return chunks;
}

/** The identifiers of an export statement's `{ … }` list, in order. */
function identifiersOf(identifiers) {
  return identifiers.split(',').map((x) => x.trim()).filter(Boolean);
}

/**
 * Rewrite a statement's `{ … }` list to `names`, keeping the layout it already
 * had: indent, one-per-line, trailing comma. Reflowing a formatter's output
 * would show up in a consumer's diff as churn unrelated to the change, and be
 * flowed straight back on their next format.
 */
function withNames(statement, names) {
  const list = statement.match(/\{[^}]*\}/)[0];
  if (!list.includes('\n')) {
    return statement.replace(/\{[^}]*\}/, () => `{ ${names.join(', ')} }`);
  }

  const indent = list.match(/\n([ \t]+)\S/)?.[1] ?? '  ';
  const closeIndent = list.match(/\n([ \t]*)\}$/)?.[1] ?? '';
  const trailing = /,\s*\}$/.test(list) ? ',' : '';
  const body = names.map((n) => indent + n).join(',\n');
  return statement.replace(/\{[^}]*\}/, () => `{\n${body}${trailing}\n${closeIndent}}`);
}

// ── Generic barrel update functions ─────────────────────────

/**
 * Update a tier-level barrel file (e.g. `content/index.js`).
 * @param {BarrelConfig} cfg
 * @param {import('./parser.js').ComponentMeta} meta
 * @param {string} outDir - absolute path to framework src dir
 * @returns {{ path: string, updated: boolean }}
 */
function updateTierBarrel(cfg, meta, outDir, prefix = 'arc') {
  const barrelPath = join(outDir, meta.tier, `index${cfg.barrelExt}`);
  // Create the barrel when a tier is new — silently skipping here left whole
  // tiers (data, typography) without barrels and thus unreachable via exports.
  if (!existsSync(barrelPath)) {
    mkdirSync(dirname(barrelPath), { recursive: true });
    writeFileSync(barrelPath, BARREL_HEADER + '\n');
  }

  const content = readFileSync(barrelPath, 'utf-8');
  const needle = cfg.existsCheck(meta);

  if (alreadyExported(content, needle)) {
    return { path: barrelPath, updated: false };
  }

  const exportLines = cfg.tierExportLines(meta, prefix);
  const updated = content.trimEnd() + cfg.separator + exportLines + '\n';
  writeFileSync(barrelPath, updated);
  return { path: barrelPath, updated: true };
}

/**
 * Update a root-level barrel file (e.g. `index.ts`).
 * Supports two strategies:
 *   - 'root-merge': merge new export name into an existing tier re-export line (WC style)
 *   - 'root-append': append new export line(s) at end of file (all frameworks)
 * @param {BarrelConfig} cfg
 * @param {import('./parser.js').ComponentMeta} meta
 * @param {string} outDir - absolute path to framework src dir
 * @returns {{ path: string, updated: boolean }}
 */
function updateRootBarrel(cfg, meta, outDir) {
  const barrelPath = join(outDir, `index${cfg.barrelExt}`);
  if (!existsSync(barrelPath)) {
    mkdirSync(dirname(barrelPath), { recursive: true });
    writeFileSync(barrelPath, BARREL_HEADER + '\n');
  }

  const content = readFileSync(barrelPath, 'utf-8');
  const needle = cfg.rootExistsCheck
    ? cfg.rootExistsCheck(meta)
    : cfg.existsCheck(meta);

  if (alreadyExported(content, needle)) {
    return { path: barrelPath, updated: false };
  }

  if (cfg.rootStrategy === 'root-merge') {
    // WC-style: try to add to an existing tier re-export.
    //
    // Unanchored, and rewritten through `withNames`, so a tier export a
    // formatter has wrapped is found and merged into rather than missed — the
    // line-anchored version wrote a second statement for the same module.
    // `[^}]*` cannot cross a `}`, so the match still begins at an `export {`
    // and ends at that statement's own brace.
    const tierExportPattern = new RegExp(
      `export\\s*\\{[^}]*\\}\\s*from\\s*['"]\\./${meta.tier}/index\\.js['"];?`
    );
    const tierMatch = content.match(tierExportPattern);

    if (tierMatch) {
      const statement = tierMatch[0];
      const names = identifiersOf(statement.match(/\{([^}]*)\}/)[1]);
      const merged = withNames(statement, [...names, meta.className]);
      writeFileSync(barrelPath, content.replace(statement, () => merged));
    } else {
      const exportLine = cfg.rootExportLines(meta);
      const updated = content.trimEnd() + '\n' + exportLine + '\n';
      writeFileSync(barrelPath, updated);
    }
  } else {
    // Append strategy — all other frameworks
    const exportLines = cfg.rootExportLines(meta);
    const updated = content.trimEnd() + cfg.separator + exportLines + '\n';
    writeFileSync(barrelPath, updated);
  }

  return { path: barrelPath, updated: true };
}

