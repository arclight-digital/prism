// ── Barrel reconciliation ───────────────────────────────────

/** Extensions a specifier may actually be on disk as. */
const SOURCE_EXTS = ['.ts', '.tsx', '.js', '.mjs', '.vue', '.svelte'];

/**
 * Resolve a relative specifier to a file on disk, or null.
 *
 * A barrel's specifier rarely matches its file verbatim: TypeScript writes
 * `./Toast.js` for `Toast.ts`, Angular omits the extension entirely, and a
 * consumer may point at a directory and mean its index. All of those must be
 * treated as resolving, or the prune below deletes working exports.
 */
function resolveSpecifier(dir, specifier) {
  const base = join(dir, specifier);
  const candidates = [base];

  const withoutJs = base.replace(/\.js$/, '');
  if (withoutJs !== base) candidates.push(...SOURCE_EXTS.map((e) => withoutJs + e));
  if (!/\.[a-z]+$/.test(base)) candidates.push(...SOURCE_EXTS.map((e) => base + e));
  // A directory specifier means that directory's barrel.
  candidates.push(...SOURCE_EXTS.map((e) => join(base, `index${e}`)));

  return candidates.find((c) => existsSync(c) && statSync(c).isFile()) ?? null;
}

/** Whether a resolved path is itself a barrel. */
function targetIsBarrel(path) {
  return /(^|[\\/])index\.[a-z]+$/.test(path);
}

/** `default as Foo` / `Foo as Bar` → the name the importer sees. */
function sourceName(identifier) {
  return identifier.split(/\s+as\s+/)[0].trim();
}

/**
 * Repair barrels that export things which no longer exist.
 *
 * The per-component updates above are append-only, which is the right shape for
 * watch and single-file mode: they see one meta and must not judge the rest of
 * the barrel on that basis. The cost is that a deleted component's export lines
 * survive forever, and the specifier points at a file the generators have stopped
 * writing — so the barrel stops compiling:
 *
 *   error TS2307: Cannot find module './ToastManager.js'
 *
 * That breaks the build of whoever imports the barrel rather than prism's own, and
 * only when someone typechecks the wrapper package. So unlike `sweepOrphans` this
 * is not gated behind --prune: an unbuildable barrel is a bug, not untidiness.
 *
 * Decided by *resolution*, never by naming convention. An earlier attempt rebuilt
 * the expected specifier set from the metas and deleted anything absent from it,
 * which quietly stripped 136 working exports from a project whose web-component
 * barrels point at `./accordion.register.js` rather than the `./accordion.js` this
 * file would have written — a barrel prism does not generate at all. Asking the
 * filesystem cannot be wrong about that.
 *
 * @param {object} config - normalized config
 * @param {string} root - project root
 * @returns {{ path: string, removed: string[] }[]} one entry per barrel changed
 */
export function pruneBarrels(config, root, metas = []) {
  // Names belonging to a component config.barrelExclude keeps out of the
  // barrels. Taken from the real metas rather than derived from the tag, so
  // this can't be wrong about how a name is spelled — the same reason the rest
  // of this function asks the filesystem instead of guessing.
  const excludedNames = new Set();
  const excluded = new Set(config.barrelExclude ?? []);
  for (const meta of metas) {
    if (!excluded.has(meta.tag)) continue;
    excludedNames.add(meta.className);
    excludedNames.add(meta.pascalName);
    excludedNames.add(`${meta.pascalName}Props`);
  }

  const dirs = [];
  if (config.components) dirs.push(join(root, config.components));
  for (const key of ['react', 'vue', 'svelte', 'angular', 'solid', 'preact']) {
    if (config[key]?.barrels) dirs.push(join(root, config[key].outDir));
  }

  const changed = [];
  for (const dir of dirs) {
    // Tier barrels before root barrels: a root barrel re-exports tier barrels by
    // identifier, so it has to see them already repaired.
    for (const tier of config.tiers) {
      record(changed, pruneBarrelFile(join(dir, tier), excludedNames));
    }
    record(changed, pruneBarrelFile(dir, excludedNames));
  }
  return changed;
}

function record(changed, results) {
  for (const r of results) if (r.removed.length > 0) changed.push(r);
}

/** Repair every barrel file directly inside `dir`. */
function pruneBarrelFile(dir, excludedNames = new Set()) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const ext of SOURCE_EXTS) {
    const path = join(dir, `index${ext}`);
    if (!existsSync(path)) continue;
    const result = repairBarrel(path, dir, excludedNames);
    if (result) out.push(result);
  }
  return out;
}

/** The name an importer sees: `default as CodeBlock` → `CodeBlock`. */
function exportedName(identifier) {
  const parts = identifier.split(/\s+as\s+/);
  return parts[parts.length - 1].trim();
}

function repairBarrel(path, dir, excludedNames = new Set()) {
  const content = readFileSync(path, 'utf-8');
  const removed = [];
  const out = [];

  for (const chunk of exportStatements(content)) {
    if (!chunk.match) { out.push(chunk.raw); continue; }

    const [, identifiers, specifier] = chunk.match;
    const resolved = resolveSpecifier(dir, specifier);

    // Unresolvable specifier: the whole statement is broken.
    if (!resolved) {
      removed.push(specifier);
      continue;
    }

    // Kept out of the barrels by config.barrelExclude. The file still exists —
    // the component is generated and reachable by its own subpath — so nothing
    // else here would drop it, and the append path never removes anything.
    if (excludedNames.size > 0) {
      const names = identifiersOf(identifiers);
      const keep = names.filter((n) => !excludedNames.has(exportedName(n)));
      if (keep.length !== names.length) {
        for (const n of names) {
          if (excludedNames.has(exportedName(n))) removed.push(exportedName(n));
        }
        if (keep.length > 0) out.push(withNames(chunk.raw, keep));
        continue;
      }
    }

    // Re-export of another barrel: the path is fine, so check that the names are
    // still there. Nothing else can catch a name that a tier barrel stopped
    // exporting — the file itself exists either way.
    if (targetIsBarrel(resolved)) {
      const targetText = readFileSync(resolved, 'utf-8');
      const names = identifiersOf(identifiers);
      const live = names.filter((n) => hasIdentifier(targetText, sourceName(n)));
      if (live.length === names.length) { out.push(chunk.raw); continue; }
      for (const n of names) {
        if (!hasIdentifier(targetText, sourceName(n))) removed.push(sourceName(n));
      }
      if (live.length > 0) out.push(withNames(chunk.raw, live));
      continue;
    }

    out.push(chunk.raw);
  }

  if (removed.length === 0) return null;
  // trimEnd + single newline, matching how the append path above writes, so a
  // prune never shows up in a diff as a whitespace change.
  writeFileSync(path, out.join('\n').trimEnd() + '\n');
  return { path, removed: [...new Set(removed)] };
}

/** Identifier-boundary search, so `Button` does not match inside `IconButton`. */
function hasIdentifier(text, name) {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(?<![\\w$])${escaped}(?![\\w$])`).test(text);
}
